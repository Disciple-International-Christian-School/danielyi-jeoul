create table if not exists discipline.audit_logs (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  action text not null check (action in ('INSERT', 'UPDATE', 'DELETE')),
  entity_type text not null,
  entity_id text,
  before_data jsonb,
  after_data jsonb,
  created_at timestamptz not null default now()
);

create index if not exists discipline_audit_logs_entity_idx
  on discipline.audit_logs (entity_type, entity_id, created_at desc);
create index if not exists discipline_audit_logs_actor_idx
  on discipline.audit_logs (actor_user_id, created_at desc)
  where actor_user_id is not null;

alter table discipline.audit_logs enable row level security;

drop policy if exists discipline_audit_logs_read_admin on discipline.audit_logs;
create policy discipline_audit_logs_read_admin on discipline.audit_logs
  for select to authenticated
  using (private.current_admin_role() is not null);

grant select on discipline.audit_logs to authenticated;

create or replace function private.write_discipline_audit_log()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_entity_id text;
begin
  if tg_op = 'DELETE' then
    v_entity_id := to_jsonb(old)->>'id';
    insert into discipline.audit_logs (
      actor_user_id, action, entity_type, entity_id, before_data, after_data
    ) values (
      auth.uid(), tg_op, tg_table_name, v_entity_id, to_jsonb(old), null
    );
    return old;
  end if;

  v_entity_id := to_jsonb(new)->>'id';

  insert into discipline.audit_logs (
    actor_user_id, action, entity_type, entity_id, before_data, after_data
  ) values (
    auth.uid(),
    tg_op,
    tg_table_name,
    v_entity_id,
    case when tg_op = 'UPDATE' then to_jsonb(old) end,
    to_jsonb(new)
  );

  return new;
end;
$$;

drop trigger if exists point_records_audit_log on public.point_records;
create trigger point_records_audit_log
