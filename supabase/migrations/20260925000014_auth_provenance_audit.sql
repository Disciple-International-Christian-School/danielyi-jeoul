create or replace function private.set_audit_actor()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    if new.created_by is null then
      new.created_by := auth.uid();
    end if;
    if new.updated_by is null then
      new.updated_by := auth.uid();
    end if;
  elsif tg_op = 'UPDATE' then
    new.updated_by := auth.uid();
  end if;
  return new;
end;
$$;

drop trigger if exists point_records_set_audit_actor on public.point_records;
create trigger point_records_set_audit_actor
  before insert or update on public.point_records
  for each row execute function private.set_audit_actor();

drop trigger if exists reflection_records_set_audit_actor on public.reflection_records;
create trigger reflection_records_set_audit_actor
  before insert or update on public.reflection_records
