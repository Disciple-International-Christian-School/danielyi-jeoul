-- Operational scoring foundation:
-- 1) raw merit/demerit totals remain separate;
-- 2) punishment decisions may use derived NET penalty = negative - positive;
-- 3) "monthly" settlement is an admin-closed period, not a calendar month.

create table public.settlement_periods (
  id bigint generated by default as identity primary key,
  label text not null,
  starts_on date not null,
  ends_on date,
  closed_at timestamptz,
  created_by uuid references auth.users(id) on delete set null default auth.uid(),
  closed_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  check (char_length(btrim(label)) between 1 and 80),
  check (ends_on is null or ends_on >= starts_on),
  check (
    (ends_on is null and closed_at is null and closed_by is null)
    or
    (ends_on is not null and closed_at is not null)
  )
);

comment on table public.settlement_periods is
  'Admin-closed accumulation periods aligned to DICS home-leave cycles. Only one period may remain open.';

create unique index settlement_periods_one_open_uq
  on public.settlement_periods ((1))
  where ends_on is null;

create index settlement_periods_dates_idx
  on public.settlement_periods (starts_on, ends_on);

alter table public.settlement_periods enable row level security;

create policy settlement_periods_read on public.settlement_periods
  for select to authenticated
  using (private.current_admin_role() is not null);

create policy settlement_periods_insert on public.settlement_periods
  for insert to authenticated
  with check (private.current_admin_role() = 'SEONDO');

create policy settlement_periods_update on public.settlement_periods
  for update to authenticated
  using (private.current_admin_role() = 'SEONDO')
  with check (private.current_admin_role() = 'SEONDO');

-- Per-student, per-week score ledger. This keeps raw totals and exposes a derived
-- penalty balance for operational decisions without destroying either source total.
create or replace view public.v_weekly_scores
with (security_invoker = true) as
select
  pr.student_id,
  date_trunc('week', pr.recorded_at::timestamp)::date as week_start,
  coalesce(sum(pr.points) filter (where pr.type = 'POSITIVE'), 0)::int as positive_points,
  coalesce(sum(pr.points) filter (where pr.type = 'NEGATIVE'), 0)::int as negative_points,
  (
    coalesce(sum(pr.points) filter (where pr.type = 'NEGATIVE'), 0)
    - coalesce(sum(pr.points) filter (where pr.type = 'POSITIVE'), 0)
  )::int as net_penalty_points,
  coalesce(count(*) filter (where pr.type = 'NEGATIVE'), 0)::int as penalty_incident_count,
  (
    coalesce(count(*) filter (where pr.type = 'NEGATIVE'), 0) >= 3
    or (
      coalesce(sum(pr.points) filter (where pr.type = 'NEGATIVE'), 0)
      - coalesce(sum(pr.points) filter (where pr.type = 'POSITIVE'), 0)
    ) >= 8
  ) as physical_training_required
from public.point_records pr
where pr.deleted_at is null
group by pr.student_id, date_trunc('week', pr.recorded_at::timestamp)::date;

-- Every period/student row, including zero-score students. The physical-training
-- count is recomputed from records inside that settlement period so no snapshot
-- or manual counter is required.
create or replace view public.v_settlement_scores
with (security_invoker = true) as
with period_students as (
  select
    sp.id as period_id,
    sp.label as period_label,
    sp.starts_on,
    coalesce(sp.ends_on, private.kst_today()) as effective_end,
    sp.ends_on,
    s.id as student_id,
    s.student_no,
    s.name as student_name,
    s.grade,
    s.homeroom
  from public.settlement_periods sp
  cross join public.students s
  where s.deleted_at is null
),
period_totals as (
  select
    ps.period_id,
    ps.student_id,
    coalesce(sum(pr.points) filter (where pr.type = 'POSITIVE'), 0)::int as positive_points,
    coalesce(sum(pr.points) filter (where pr.type = 'NEGATIVE'), 0)::int as negative_points
  from period_students ps
  left join public.point_records pr
    on pr.student_id = ps.student_id
   and pr.deleted_at is null
   and pr.recorded_at between ps.starts_on and ps.effective_end
  group by ps.period_id, ps.student_id
),
period_weekly as (
  select
    ps.period_id,
    pr.student_id,
    date_trunc('week', pr.recorded_at::timestamp)::date as week_start,
    coalesce(sum(pr.points) filter (where pr.type = 'POSITIVE'), 0)::int as positive_points,
    coalesce(sum(pr.points) filter (where pr.type = 'NEGATIVE'), 0)::int as negative_points,
    coalesce(count(*) filter (where pr.type = 'NEGATIVE'), 0)::int as penalty_incident_count
  from period_students ps
  join public.point_records pr
    on pr.student_id = ps.student_id
   and pr.deleted_at is null
   and pr.recorded_at between ps.starts_on and ps.effective_end
  group by ps.period_id, pr.student_id, date_trunc('week', pr.recorded_at::timestamp)::date
),
training_counts as (
  select
    period_id,
    student_id,
    count(*) filter (
      where penalty_incident_count >= 3
         or (negative_points - positive_points) >= 8
    )::int as physical_training_weeks
  from period_weekly
  group by period_id, student_id
)
select
  ps.period_id,
  ps.period_label,
  ps.starts_on,
  ps.ends_on,
  ps.effective_end,
  (ps.ends_on is null) as is_open,
  ps.student_id,
  ps.student_no,
  ps.student_name,
  ps.grade,
  ps.homeroom,
  pt.positive_points,
  pt.negative_points,
  (pt.negative_points - pt.positive_points)::int as net_penalty_points,
  coalesce(tc.physical_training_weeks, 0)::int as physical_training_weeks,
  (
    coalesce(tc.physical_training_weeks, 0) >= 3
    or (pt.negative_points - pt.positive_points) >= 20
  ) as committee_required
from period_students ps
join period_totals pt
  on pt.period_id = ps.period_id and pt.student_id = ps.student_id
left join training_counts tc
  on tc.period_id = ps.period_id and tc.student_id = ps.student_id;

create or replace function public.start_settlement_period(
  p_starts_on date,
  p_label text
)
returns bigint
language plpgsql
set search_path = ''
as $$
declare
  v_id bigint;
begin
  if private.current_admin_role() <> 'SEONDO' then
    raise exception '선도부 관리자만 정산기간을 시작할 수 있습니다.';
  end if;

  if exists (select 1 from public.settlement_periods where ends_on is null) then
    raise exception '이미 진행 중인 정산기간이 있습니다.';
  end if;

  insert into public.settlement_periods (label, starts_on)
  values (btrim(p_label), p_starts_on)
  returning id into v_id;

  return v_id;
end;
$$;

create or replace function public.close_settlement_period(
  p_period_id bigint,
  p_end_date date,
  p_open_next boolean default true,
  p_next_label text default null
)
returns bigint
language plpgsql
set search_path = ''
as $$
declare
  v_period public.settlement_periods%rowtype;
  v_next_id bigint;
begin
  if private.current_admin_role() <> 'SEONDO' then
    raise exception '선도부 관리자만 정산기간을 종료할 수 있습니다.';
  end if;

  select * into v_period
  from public.settlement_periods
  where id = p_period_id and ends_on is null
  for update;

  if v_period.id is null then
    raise exception '진행 중인 정산기간을 찾을 수 없습니다.';
  end if;

  if p_end_date < v_period.starts_on then
    raise exception '종료일은 시작일보다 빠를 수 없습니다.';
  end if;

  update public.settlement_periods
  set ends_on = p_end_date,
      closed_at = now(),
      closed_by = auth.uid()
  where id = p_period_id;

  if p_open_next then
    insert into public.settlement_periods (label, starts_on)
    values (
      coalesce(nullif(btrim(p_next_label), ''), to_char(p_end_date + 1, 'YYYY-MM-DD') || ' 시작'),
      p_end_date + 1
    )
    returning id into v_next_id;
  end if;

  return v_next_id;
end;
$$;

grant execute on function public.start_settlement_period(date, text) to authenticated;
grant execute on function public.close_settlement_period(bigint, date, boolean, text) to authenticated;
