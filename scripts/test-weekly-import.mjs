import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
const compiled = ts.transpileModule(readFileSync(new URL('../src/lib/weekly-import.ts', import.meta.url), 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const { parseWeeklyWorkbook } = await import('data:text/javascript;base64,' + Buffer.from(compiled).toString('base64'));
const workbook = (rows, sheet = '26/10/19~10/25') => [{ sheet, data: [['학년','이름','상점','벌점','총점수'], ...rows] }];
const parse = rows => parseWeeklyWorkbook(workbook(rows), '2026-10-26');
const preview = parse([['G7','가상학생','','',0],['G7','가상학생','',4,-4],['G9-A','테스트',100,2,98]]);
assert.equal(preview.rows.length, 3);
assert.equal(preview.weeks[0].students, 2);
assert.equal(preview.weeks[0].positive, 100);
assert.equal(preview.weeks[0].negative, 6);
assert.equal(preview.rows[0].raw.cells[2], '');
assert.throws(() => parse([['G7','테스트',0,3,-3],['G7','테스트',0,4,-4]]), /서로 다릅니다/);
assert.throws(() => parse([['G7','테스트',0,3,3]]), /최종값/);
assert.throws(() => parse([['G7','테스트',0,-3,3]]), /최종값/);
assert.throws(() => parseWeeklyWorkbook(workbook([['G7','테스트',0,3,-3]], '26/10/26~11/1'), '2026-10-26'), /확정 탭/);
assert.throws(() => parseWeeklyWorkbook(workbook([], '26/10/20~10/26'), '2026-10-26'), /월~일/);
const corrected = parseWeeklyWorkbook([...workbook([['G7','가상학생',0,1,-1]], '26/10/12~10/18'), ...workbook([['오타','가상학생',0,8,-8]])], '2026-10-26');
assert.equal(corrected.rows[1].grade, 7);
assert.equal(corrected.rows[1].raw.cells[0], '오타');
assert.equal(corrected.weeks[1].negative, 8);
assert.equal(corrected.warnings.length, 1);
console.log('weekly-import: duplicate, sign, boundary, original blank, and validation checks passed');
